/** แปลงเลขอารบิก 0-9 เป็นเลขไทย ๐-๙ */
export function convertToThaiNumerals(text: string): string {
  const thaiDigits = ["๐", "๑", "๒", "๓", "๔", "๕", "๖", "๗", "๘", "๙"];
  return text.replace(/[0-9]/g, (char) => thaiDigits[parseInt(char, 10)]);
}
